#!/usr/bin/env python3
"""Generate every site-wide file from the manifests. One command wires a guide into the site.

  python3 _tools/build-site.py            write what changed, then refresh the Russian edition (ru_pages.py)
  python3 _tools/build-site.py --check    compare only: write nothing, exit 1 if any file is out of date

Sources (the only places to edit):
  _tools/site.json                      site block, external links, categories: id, titles and the guides in display order
  _tools/articles/<slug>/meta.json      a generated guide: codename, label {en, ru}, llms, related, freshness
  _tools/handmade/<slug>/meta.json      the same for a hand-made guide (and the two time-philosophy pages)

Generated (never edit by hand; --check and check-all.sh fail if they differ from the manifests):
  pages.json              site block, external links, categories -> pages (slug, codename, label) and planned rows
  index.html              only the guide lists between the <!-- guides … --> and <!-- /guides --> markers
  llms.txt                everything from the first "## " heading on; the introduction above it is hand-written
  related.json            slug -> related slugs ("See also")
  _tools/freshness.json   one row per dated claim, for .github/workflows/freshness.yml
  search.json             descriptions + chapter headings read from the pages (search-index.py)
  sitemap.xml             the index and every guide, with the Russian edition and hreflang alternates where ru/<slug>.html exists

Order matters only for the sitemap, which lists the Russian pages that exist: a normal run writes pages.json and
index.html, runs ru_pages.py (ru/index.html is made from index.html, a new guide gets its ru/ page), then writes the
sitemap. A file is written only when its bytes change. Mission of the day: every row of a guide's MOD.json must be in
assets/mission-of-day.js by date and guide (that file is shared with another site and stays hand-edited); missing rows
are reported, not fatal.
"""
import glob, html, importlib.util, json, os, re, subprocess, sys

T = os.path.dirname(os.path.abspath(__file__))
R = os.path.dirname(T)
J = lambda v: json.dumps(v, ensure_ascii=False)
E = html.escape
INDEX_OPEN = '    <!-- guides: generated by _tools/build-site.py from _tools/site.json and the guides\' meta.json; edit those, not this list -->\n'
INDEX_CLOSE = '    <!-- /guides -->\n'
INDEX_RX = re.compile(r'[ \t]*<!-- guides:[^\n]*-->\n[\s\S]*?[ \t]*<!-- /guides -->\n')

_spec = importlib.util.spec_from_file_location('search_index', os.path.join(T, 'search-index.py'))
search_index = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(search_index)


def read(rel):
    p = os.path.join(R, rel)
    return open(p, encoding='utf-8').read() if os.path.exists(p) else None


def manifest_path(slug):
    for kind in ('articles', 'handmade'):
        p = os.path.join(T, kind, slug, 'meta.json')
        if os.path.exists(p):
            return p
    return None


def load():
    """site.json and the manifests of the guides it lists -> (site, categories, guides by slug, ordered slugs, problems, notes)."""
    site = json.load(open(os.path.join(T, 'site.json'), encoding='utf-8'))
    bad, notes, guides, slugs = [], [], {}, []
    for c in site['categories']:
        c['slugs'] = [g for g in c['guides'] if isinstance(g, str)]
        for g in c['guides']:
            if not isinstance(g, str) and not (isinstance(g, dict) and len(g) == 1 and next(iter(g)) in ('planned', 'external_links', 'also')):
                bad.append('site.json: category %s has an entry that is not a slug, planned, external_links or also: %s' % (c['id'], J(g)))
        for s in c['slugs']:
            if s in guides:
                bad.append('site.json: %s is listed twice (use {"also": slug} for a second listing on the index page)' % s)
                continue
            p = manifest_path(s)
            if not p:
                bad.append('no manifest for %s (expected _tools/articles/%s/meta.json or _tools/handmade/%s/meta.json)' % (s, s, s.rstrip('/')))
                continue
            m = json.load(open(p, encoding='utf-8'))
            rel = os.path.relpath(p, R)
            if m.get('slug') != s:
                bad.append('%s: "slug" is %s, the folder says %s' % (rel, J(m.get('slug')), s))
            for k in ('codename', 'llms'):
                if not isinstance(m.get(k), str) or not m[k].strip():
                    bad.append('%s: "%s" is missing' % (rel, k))
            if not (isinstance(m.get('label'), dict) and m['label'].get('en') and m['label'].get('ru')):
                bad.append('%s: "label" needs "en" and "ru"' % rel)
            if not isinstance(m.get('related'), list):
                bad.append('%s: "related" must be a list of slugs' % rel)
            for row in m.get('freshness', []):
                if sorted(row) != ['claim', 'review_by', 'source'] or not re.fullmatch(r'\d{4}-\d\d-\d\d', str(row.get('review_by'))):
                    bad.append('%s: a freshness row needs exactly claim, source, review_by (YYYY-MM-DD): %s' % (rel, J(row)))
            if not os.path.exists(search_index.page_file(s)):
                bad.append('%s: the page %s does not exist' % (s, os.path.relpath(search_index.page_file(s), R)))
            guides[s] = m
            slugs.append(s)
    for c in site['categories']:
        bad += ['site.json: category %s cross-lists %s, which is not a guide' % (c['id'], g['also'])
                for g in c['guides'] if isinstance(g, dict) and 'also' in g and g['also'] not in guides]
    if not bad:
        bad += search_index.related_problems({s: guides[s]['related'] for s in slugs}, slugs)
    for p in sorted(glob.glob(os.path.join(T, 'articles', '*', 'meta.json')) + glob.glob(os.path.join(T, 'handmade', '**', 'meta.json'), recursive=True)):
        s = json.load(open(p, encoding='utf-8')).get('slug')
        if s not in guides:
            notes.append('%s is not listed in site.json, so %s is not on the site' % (os.path.relpath(p, R), s))
    return site, guides, slugs, bad, notes


# ---- the generated files -------------------------------------------------------------------------------------------

def label(d):
    return '{ "en": %s, "ru": %s }' % (J(d['en']), J(d['ru']))


def pages_json(site, guides):
    s = site['site']
    out = ['{', '  "site": {', '    "base": %s,' % J(s['base']), '    "url": %s,' % J(s['url']), '    "title": %s' % label(s['title']), '  },',
           '  "external": [', ',\n'.join('    { "label": %s, "url": %s }' % (J(e['label']), J(e['url'])) for e in site['external']), '  ],',
           '  "categories": [']
    cats = []
    for c in site['categories']:
        t = ['    {', '      "id": %s,' % J(c['id']), '      "title": %s,' % label(c['title']), '      "pages": [',
             ',\n'.join('        { "slug": %s, "codename": %s, "label": %s }' % (J(x), J(guides[x]['codename']), label(guides[x]['label'])) for x in c['slugs'])]
        planned = [g['planned'] for g in c['guides'] if isinstance(g, dict) and 'planned' in g]
        if planned:
            t += ['      ],', '      "planned": [', ',\n'.join('        { "label": %s }' % label(p) for p in planned)]
        cats.append('\n'.join(t + ['      ]', '    }']))
    return '\n'.join(out + [',\n'.join(cats), '  ]', '}']) + '\n'


def index_lists(site, guides):
    """The marked region of index.html: one block per category, rows in site.json order."""
    def row(g):
        if isinstance(g, dict) and 'planned' in g:
            p = g['planned']
            return ['<li class="soon"><span class="np"><span class="cn" data-en="SOON" data-ru="СКОРО">SOON</span>'
                    '<span class="cl" data-en="%s" data-ru="%s">%s</span></span></li>' % (E(p['en']), E(p['ru']), E(p['en']))]
        if isinstance(g, dict) and 'external_links' in g:
            return ['<li class="ext"><a href="%s" rel="external noopener" target="_blank"><span class="cn">EXT&#8599;</span>'
                    '<span class="cl">%s</span></a></li>' % (E(e['url']), E(e['label'])) for e in site['external']]
        s = g['also'] if isinstance(g, dict) else g
        m = guides[s]
        return ['<li><a href="/aerospace/%s"><span class="cn">%s</span><span class="cl" data-en="%s" data-ru="%s">%s</span></a></li>'
                % (s, E(m['codename']), E(m['label']['en']), E(m['label']['ru']), E(m['label']['en']))]
    out = INDEX_OPEN + '\n'
    for c in site['categories']:
        t = c['title']
        out += ('    <div class="hub-cat" data-cat="%s">\n      <h2 data-en="%s" data-ru="%s">%s</h2>\n      <ul>\n'
                % (c['id'], E(t['en']), E(t['ru']), E(t['en'])))
        out += ''.join('        %s\n' % r for g in c['guides'] for r in row(g))
        out += '      </ul>\n    </div>\n\n'
    return out + INDEX_CLOSE


def index_html(site, guides, cur, bad):
    if cur is None or len(INDEX_RX.findall(cur)) != 1:
        bad.append('index.html: expected exactly one <!-- guides: … --> … <!-- /guides --> region')
        return cur
    region = index_lists(site, guides)
    return INDEX_RX.sub(lambda m: region, cur)


def llms_txt(site, guides, cur, bad):
    if cur is None or '\n## ' not in cur:
        bad.append('llms.txt: no "## " heading to mark where the generated part starts')
        return cur
    head = cur[:cur.index('\n## ') + 1]
    url = site['site']['url']
    return head + '\n\n'.join('## %s\n\n' % c['title']['en'] + '\n'.join(
        '- [%s](%s%s): %s' % (guides[s]['label']['en'], url, s, guides[s]['llms']) for s in c['slugs']) for c in site['categories']) + '\n'


def related_json(site, guides, slugs):
    legacy = [s for s in site.get('legacy_order', {}).get('related', []) if s in guides]
    order = legacy + [s for s in slugs if s not in legacy]
    return '{\n  "_about": %s,\n%s\n}\n' % (J(site['about']['related']), ',\n'.join(
        '  %s: [%s]' % (J(s), ', '.join(J(x) for x in guides[s]['related'])) for s in order))


def freshness_json(site, guides, slugs):
    rows = {s: list(guides[s].get('freshness', [])) for s in slugs}
    taken = {s: 0 for s in slugs}
    out = []
    for s in site.get('legacy_order', {}).get('freshness', []):      # the n-th mention of a guide = its n-th row
        if s in rows and taken[s] < len(rows[s]):
            out.append((s, rows[s][taken[s]])); taken[s] += 1
    rest = [(r['review_by'], i, n, s, r) for i, s in enumerate(slugs) for n, r in enumerate(rows[s]) if n >= taken[s]]
    out += [(s, r) for _, _, _, s, r in sorted(rest, key=lambda x: x[:3])]
    return '{\n  "_about": %s,\n  "items": [\n%s\n  ]\n}\n' % (J(site['about']['freshness']), ',\n'.join(
        '    ' + J({'page': s, 'claim': r['claim'], 'source': r['source'], 'review_by': r['review_by']}) for s, r in out))


def sitemap_xml(site, slugs):
    """Exactly what .github/workflows/sitemap.yml used to print: a guide with ru/<slug>.html is listed twice, each URL naming both."""
    base = site['site']['url'].rstrip('/')
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">']
    for s in [''] + slugs:
        en, ru = '%s/%s' % (base, s), '%s/ru/%s' % (base, s)
        if os.path.isfile(os.path.join(R, 'ru', (s or 'index') + '.html')):
            out += ['  <url><loc>%s</loc><xhtml:link rel="alternate" hreflang="en" href="%s"/><xhtml:link rel="alternate" hreflang="ru" href="%s"/>'
                    '<xhtml:link rel="alternate" hreflang="x-default" href="%s"/></url>' % (u, en, ru, en) for u in (en, ru)]
        else:
            out.append('  <url><loc>%s</loc></url>' % en)
    return '\n'.join(out + ['</urlset>']) + '\n'


# ---- mission of the day (report only) ------------------------------------------------------------------------------

def mission_gaps(guides):
    """(missing, reworded): MOD.json rows (the 8 fields of a row of M in assets/mission-of-day.js) with no row of the same date
    and guide in the widget, and the number of rows per guide that are there with different wording (the widget's text
    is edited in place, so it is the current one)."""
    js = read('assets/mission-of-day.js') or ''
    unq = lambda x: re.sub(r'\\u([0-9a-fA-F]{4})', lambda m: chr(int(m.group(1), 16)), x).replace("\\'", "'").replace('\\\\', '\\')
    have = {}
    for line in re.findall(r"^\['\d{4}-\d\d-\d\d',.*\],?\s*$", js, re.M):
        f = [unq(x) for x in re.findall(r"'((?:[^'\\]|\\.)*)'", line)]
        have.setdefault((f[0], f[4]), []).append(f)
    missing, reworded = [], {}
    for p in sorted(glob.glob(os.path.join(T, 'articles', '*', 'MOD.json')) + glob.glob(os.path.join(T, 'handmade', '**', 'MOD.json'), recursive=True)):
        for row in json.load(open(p, encoding='utf-8')):
            row = [str(x) for x in row]
            same = have.get((row[0], row[4]), [])
            if not same:
                missing.append('%s: %s "%s" (%s)' % (os.path.relpath(p, R), row[0], row[1], row[4]))
            elif row not in same:
                reworded[row[4]] = reworded.get(row[4], 0) + 1
    linked = {k[1] for k in have if k[1]}
    missing += ['mission-of-day.js links to /aerospace/%s, which is not a guide' % s for s in sorted(linked - set(guides))]
    return missing, reworded


# ---- main ----------------------------------------------------------------------------------------------------------

def main():
    args = sys.argv[1:]
    if [a for a in args if a != '--check']:
        print(__doc__.strip()); sys.exit(0 if args[0] in ('-h', '--help') else 2)
    check = '--check' in args
    site, guides, slugs, bad, notes = load()
    if bad:
        print('build-site: the manifests have problems, nothing written\n  ' + '\n  '.join(bad)); sys.exit(1)
    files = [('pages.json', lambda: pages_json(site, guides)),
             ('index.html', lambda: index_html(site, guides, read('index.html'), bad)),
             ('llms.txt', lambda: llms_txt(site, guides, read('llms.txt'), bad)),
             ('related.json', lambda: related_json(site, guides, slugs)),
             ('_tools/freshness.json', lambda: freshness_json(site, guides, slugs)),
             ('search.json', lambda: search_index.index_text(slugs)),
             ('sitemap.xml', lambda: sitemap_xml(site, slugs))]
    stale = []
    for rel, make in files:
        if rel == 'sitemap.xml' and not check:      # it lists the Russian pages that exist, so they come first
            r = subprocess.run([sys.executable, os.path.join(T, 'ru_pages.py')], capture_output=True, text=True)
            print('   ' + (r.stdout + r.stderr).strip().replace('\n', '\n   '))
            if r.returncode:
                sys.exit('build-site: ru_pages.py failed; sitemap.xml not written')
        new = make()
        if bad:
            print('build-site: ' + '\n  '.join(bad)); sys.exit(1)
        if new != read(rel):
            stale.append(rel)
            if not check:
                with open(os.path.join(R, rel), 'w', encoding='utf-8') as f:
                    f.write(new)
    dates = json.load(open(os.path.join(T, 'dates.json'), encoding='utf-8'))
    notes += ['%s has no dates in _tools/dates.json: run python3 _tools/finalize.py --touch %s, then python3 _tools/ru_pages.py' % (s, s)
              for s in slugs if os.path.exists(os.path.join(R, s + '.html')) and s + '.html' not in dates]
    missing, reworded = mission_gaps(guides)
    n = '%d guides in %d categories' % (len(slugs), len(site['categories']))
    if check:
        print('build-site --check: %s; out of date: %s' % (n, ', '.join(stale) or 'none'))
        if stale:
            print('   run python3 _tools/build-site.py (the manifests in _tools/ are the source; do not edit these files by hand)')
    else:
        print('build-site: %s; wrote: %s' % (n, ', '.join(stale) or 'nothing, all current'))
    for x in notes:
        print('   note: ' + x)
    print('   mission of the day: %d MOD.json row(s) missing from assets/mission-of-day.js%s' % (len(missing), ':' if missing else ''))
    for x in missing:
        print('     ' + x)
    if reworded:
        print('     (present with later wording in mission-of-day.js, which is the current text: %s)'
              % ', '.join('%s %d' % kv for kv in sorted(reworded.items())))
    sys.exit(1 if check and stale else 0)


if __name__ == '__main__':
    main()
