module.exports = (w, C) => {
  const out = [], ok = (n, c, v) => out.push((c ? 'PASS ' : 'FAIL ') + n + (v !== undefined ? ' = ' + v : ''));
  const R = C.R_V;
  const P = C.period(R + C.ALT_P, R + C.ALT_A)/3600;
  ok('mapping-orbit period from Table 1-1 elements ≈ 3.259 h [4]', Math.abs(P - 3.259) < 0.005, P.toFixed(4));
  const gHi = C.geometry(10), gLo = C.geometry(90);
  ok('ground-range res at θ = 45.7° ≈ 120 m (published 120–300 m)', Math.abs(88/Math.sin(45.7*Math.PI/180) - 123) < 1 && Math.abs(gHi.ground - 123) < 1, gHi.ground.toFixed(1));
  ok('ground-range res at θ = 16.5° ≈ 300 m', Math.abs(gLo.ground - 310) < 1, gLo.ground.toFixed(1));
  const ideal = 299792458/(2*C.BW);
  ok('ideal c/2B = 66 m, below the 88 m effective value', Math.abs(ideal - 66.3) < 0.1 && ideal < 88, ideal.toFixed(2));
  const bw = C.LAMBDA/C.D_ANT*180/Math.PI;
  ok('λ/D = 1.95° ≈ measured 2.1° × 2.5° beam', bw > 1.8 && bw < 2.1, bw.toFixed(3));
  ok('periapsis altitude 289 km at 9.5° N', Math.abs(C.altitude(9.5) - 289) < 0.01);
  const a75 = C.altitude(-75);
  ok('altitude at 75° S within 5% of guide\'s 2,400 km near 74° S [3]', Math.abs(a75/2400 - 1) < 0.05, a75.toFixed(0));
  const a90 = C.altitude(90);
  ok('altitude over the north pole between 2,000 [4] and 2,300 km', a90 > 2000 && a90 < 2300, a90.toFixed(0));
  ok('incidence table endpoints 16.5° / 45.7° / 16.3°', C.incidence(90) === 16.5 && C.incidence(10) === 45.7 && C.incidence(-75) === 16.3);
  ok('incidence interpolates (12.5° → 45.6°)', Math.abs(C.incidence(12.5) - 45.6) < 1e-9, C.incidence(12.5));
  ok('real-aperture footprint at periapsis > 10 km', gHi.beam > 10, gHi.beam.toFixed(1));
  ok('echo delay at periapsis ≈ 2ρ/c', Math.abs(gHi.delay - 2*gHi.rho/299792.458*1000) < 1e-9 && gHi.delay > 1.9, gHi.delay.toFixed(3));
  const sp = C.spacing(0, 3.259);
  ok('equator strip spacing ≈ 21 km < 25 km strip', Math.abs(sp - 21.25) < 0.05, sp.toFixed(2));
  ok('overlap 25 − 21.2 within 2 km of the guide\'s ~5 km average [3]', Math.abs((25 - sp) - 5) < 2, (25 - sp).toFixed(2));
  const orb = C.T_ROT/3.259;
  ok('orbits per 243-day cycle ≈ 1,790 [4]', Math.abs(orb - 1790) < 1, orb.toFixed(1));
  ok('Venus sidereal day 5,832.6 h = 243.0 d', Math.abs(C.T_ROT/24 - 243.03) < 0.01);
  const dv = C.dvPropulsive();
  ok('propulsive Δv 8,467 → 541 km apoapsis ≈ 1.22 km/s', Math.abs(dv - 1220) < 5, dv.toFixed(1));
  const pf = C.period(C.RP_AB, C.RA1)/60;
  ok('final 541 × 197 km period ≈ 94.5 min', Math.abs(pf - 94.5) < 0.2, pf.toFixed(2));
  ok('apoapsis drop 7,926 km = “nearly 8,000” [7]', 8467 - 541 === 7926);
  const ab = C.aerobrake(1.6);
  ok('1.6 m/s per pass → >700 passes in ~70 days [6][7]', ab.passes > 700 && ab.passes < 800 && Math.abs(ab.days - 70) < 5, ab.passes + ' passes, ' + ab.days.toFixed(1) + ' d');
  const ab5 = C.aerobrake(5);
  ok('harder braking → fewer passes', ab5.passes < ab.passes && ab5.days < ab.days);
  const last = ab.hist[ab.hist.length - 1][1];
  ok('aerobrake ends at 541 km apoapsis', Math.abs(last - 541) < 1e-6);
  const mp = C.propellant(1100, dv, 220);
  ok('thrusters would need ≈ 475 kg hydrazine, > 3 × the 132.5 kg loaded', Math.abs(mp - 475) < 3 && mp > 3*132.5, mp.toFixed(1));
  const dvLoad = C.dvFromProp(1100, 132.5, 220), share = dvLoad/dv;
  ok('full launch load gives “only about a quarter” of the Δv (text, CH5)', share > 0.2 && share < 0.3, (share*100).toFixed(1) + '%');
  ok('…for any assumed mass 1,000–1,400 kg: 17–25 %, far short either way', [1000, 1400].every(m => { const r = C.dvFromProp(m, 132.5, 220)/dv; return r > 0.17 && r < 0.26; }), [1000, 1400].map(m => (C.dvFromProp(m, 132.5, 220)/dv*100).toFixed(1) + '%').join(' / '));
  ok('rocket equation round trip', Math.abs(C.dvFromProp(1100, C.propellant(1100, 500, 220), 220) - 500) < 1e-6);
  const dv140 = (Math.sqrt(C.GM_V*2*(R + 8467)/((R + 140)*(2*R + 140 + 8467))) - Math.sqrt(C.GM_V*2*(R + 541)/((R + 140)*(2*R + 140 + 541))))*1000;
  ok('periapsis 140 km instead of 197 changes total Δv by ~1 m/s (note, CH5)', Math.abs(dv140 - dv) < 2, (dv140 - dv).toFixed(2) + ' m/s');
  ok('size parameter: green light ≈ 11.4, 12.6 cm ≈ 5.0e-5', Math.abs(C.sizeParam(1e-6, 0.55e-6) - 11.42) < 0.01 && Math.abs(C.sizeParam(1e-6, 0.126) - 4.99e-5) < 1e-7);
  ok('crater model uses the 912-crater catalogue [16]', C.N_CRATERS === 912);
  const list = C.craters(912, 1990), again = C.craters(912, 1990);
  ok('crater generator is deterministic', JSON.stringify(list) === JSON.stringify(again));
  const n1 = C.countBand(list, 0.1), n5 = C.countBand(list, 0.5);
  ok('10 % band count within 3σ of 91.2', Math.abs(n1 - 91.2) < 3*C.bandSd(912, 0.1), n1);
  ok('half-sphere band count within 3σ of 456', Math.abs(n5 - 456) < 3*C.bandSd(912, 0.5), n5);
  ok('binomial sd at f = 0.5 is 15.1, not √456 = 21.4', Math.abs(C.bandSd(912, 0.5) - 15.10) < 0.01, C.bandSd(912, 0.5).toFixed(2));
  let tot = 0, sq = 0; for(let s = 1; s <= 400; s++){ const c = C.countBand(C.craters(912, s), 0.5); tot += c; sq += c*c; }
  const mean = tot/400, sdEmp = Math.sqrt(sq/400 - mean*mean);
  ok('400 throws: mean ≈ 456 and spread matches the binomial sd', Math.abs(mean - 456) < 2.5 && Math.abs(sdEmp/C.bandSd(912, 0.5) - 1) < 0.15, mean.toFixed(1) + ' ± ' + sdEmp.toFixed(1));
  ok('Venus surface 4.60 × 10⁸ km²', Math.abs(4*Math.PI*R*R/1e8 - 4.602) < 0.001);
  const d = w.document;
  ok('HUD shows altitude and resolution', /km/.test(d.getElementById('hud-alt').textContent) && /m/.test(d.getElementById('hud-vel').textContent), d.getElementById('hud-alt').textContent + ' / ' + d.getElementById('hud-vel').textContent);
  d.querySelector('#gPre .btn[data-v="90"]').click();
  ok('north-pole preset → 310 m readout', /310/.test(d.getElementById('gReadout').textContent));
  const cx0 = d.querySelector('#kSvg circle').getAttribute('cx'); d.getElementById('kThrow').click();
  ok('throw again redraws 912 new craters', d.querySelectorAll('#kSvg circle').length === 912 && d.querySelector('#kSvg circle').getAttribute('cx') !== cx0);
  d.querySelector('#gPre .btn[data-v="10"]').click();
  ok('CH2 label says resolution cell, not aperture', /SAR resolution cell: 120 m/.test(d.getElementById('gSvg').textContent) && !/synthetic aperture: 120/.test(d.getElementById('gSvg').textContent));
  ok('periapsis status: oblique, not steep', /oblique/.test(d.getElementById('gStatus').textContent) && !/steep/.test(d.getElementById('gStatus').textContent));
  d.querySelector('#rPre .btn[data-l="1.01e-6"]').click();
  ok('1.0 µm window: glow leaks through, blurred', /leaks through/.test(d.getElementById('rStatus').textContent), C.sizeParam(1e-6, 1.01e-6).toFixed(2));
  d.querySelector('#rPre .btn[data-l="0.55e-6"]').click();
  ok('green light: clouds only', /clouds show only themselves/.test(d.getElementById('rStatus').textContent));
  ok('sliders carry aria-valuetext', ['gLat','mLat','mP','mW','kF','aDv','aM'].every(id => (d.getElementById(id).getAttribute('aria-valuetext') || '').length > 1), d.getElementById('kF').getAttribute('aria-valuetext'));
  const txtAll = d.body.textContent;
  ok('no "never seen from orbit" claim left', !/never seen the|has ever seen|never seen Venus/.test(txtAll));
  d.querySelector('#langtoggle button[data-lang="ru"]').click();
  ok('RU readouts use decimal comma and Russian units', /км/.test(d.getElementById('gReadout').textContent) && /3,26|3,25/.test(d.getElementById('mPVal').textContent), d.getElementById('mPVal').textContent);
  ok('RU aria-labels applied', d.getElementById('kSvg').getAttribute('aria-label').startsWith('Равновеликая'));
  d.querySelector('#langtoggle button[data-lang="en"]').click();
  console.log(out.join('\n'));
};
